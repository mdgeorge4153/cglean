"""Chooses which compiled Lean modules go into the WebAssembly build.

Every compiled Lean module has an initializer, which runs that module's
top-level setup (closed terms, `initialize` declarations, ...) after calling
the initializers of the modules it imports. Starting from the entry module,
this follows those calls to find the modules that must be linked.

Two things keep that set small:

* Under Lean's module system, each initializer comes in two halves:
  `runtime_initialize_M` (what compiled code needs) and `meta_initialize_M`
  (what the elaborator needs, e.g. registering tactics). Only the runtime
  halves are followed.

* Even so, Mathlib's definition files `public import` tactics (for attributes
  like `@[to_dual]`), so the runtime halves still reach the tactic framework
  and through it all of Lean's elaborator. The chain is cut at the modules
  matching CUT: their initializers become no-ops and they are not linked.
  If code we do link uses anything from a cut module, linking fails with an
  undefined symbol rather than misbehaving at runtime; see borrowed.c.

Modules that don't use the module system (currently all of CGLean) have only
a combined initializer. Their C is rewritten to call the runtime halves of
their imports instead.

Usage: prune.py ENTRY_MODULE OUTDIR C_ROOT...
Writes OUTDIR/c/*.c (rewritten copies), OUTDIR/stubs.c, OUTDIR/sources.txt,
and prints the initializer symbol of the entry module.
"""

import collections
import glob
import os
import re
import sys

CUT = re.compile(
    r'^(?:runtime_|meta_)?initialize_(?:'
    r'Lean(?:_|$)|'
    r'mathlib_Mathlib_(?:Tactic|Util|Lean)_|'
    r'batteries_Batteries_(?:Tactic|Lean|Util|CodeAction)_|'
    r'(?:aesop|Qq|plausible|proofwidgets|LeanSearchClient|importGraph)_)'
)

DEFN = re.compile(
    r'^LEAN_EXPORT lean_object\* ((?:runtime_|meta_)?initialize_\w+)\(uint8_t builtin\)\s*\{(.*?)^\}',
    re.M | re.S)
CALL = re.compile(r'\b((?:runtime_|meta_)?initialize_\w+)\(builtin\)')


def main():
    entry_module, outdir, roots = sys.argv[1], sys.argv[2], sys.argv[3:]

    body, where = {}, {}
    for root in roots:
        for f in glob.glob(os.path.join(root, '**', '*.c'), recursive=True):
            with open(f, errors='replace') as h:
                for name, b in DEFN.findall(h.read()):
                    body.setdefault(name, b)
                    where.setdefault(name, f)

    def runtime_half(name):
        """The runtime half of an initializer, when the module has one. Otherwise
        the name as given, which also covers cut modules whose C we don't have."""
        base = re.sub(r'^(?:runtime_|meta_)', '', name)
        return 'runtime_' + base if 'runtime_' + base in body else name

    # The entry module's initializer, whatever package prefix Lake gave it.
    mangled = entry_module.replace('.', '_')
    entry = [n for n in body
             if n == 'initialize_' + mangled or re.fullmatch(r'initialize_[A-Za-z0-9]+_' + mangled, n)]
    if len(entry) != 1:
        sys.exit(f'prune.py: cannot find a unique initializer for {entry_module}: {entry}')
    entry = entry[0]

    seen, stubs, files, parent = set(), set(), [], {}
    todo = [runtime_half(entry)]
    while todo:
        n = todo.pop()
        if n in seen:
            continue
        seen.add(n)
        if CUT.match(n):
            stubs.add(n)
            continue
        if n not in body:
            sys.exit(f'prune.py: no C found for {n} (needed by {parent.get(n)})')
        if where[n] not in files:
            files.append(where[n])
        for c in CALL.findall(body[n]):
            if c.startswith('meta_') or c == n:
                continue
            c = runtime_half(c)
            parent.setdefault(c, n)
            todo.append(c)

    os.makedirs(os.path.join(outdir, 'c'), exist_ok=True)
    sources = []
    for f in files:
        with open(f, errors='replace') as h:
            s = h.read()
        if 'LEAN_EXPORT lean_object* runtime_initialize_' in s:
            sources.append(f)
            continue
        # Not a module-system file: call the runtime halves of its imports.
        s = CALL.sub(lambda m: runtime_half(m.group(1)) + '(builtin)', s)
        s = re.sub(r'^lean_object\* (initialize_\w+)\(uint8_t builtin\);',
                   lambda m: f'lean_object* {runtime_half(m.group(1))}(uint8_t builtin);', s, flags=re.M)
        out = os.path.join(outdir, 'c', os.path.basename(f))
        with open(out, 'w') as h:
            h.write(s)
        sources.append(out)

    with open(os.path.join(outdir, 'stubs.c'), 'w') as h:
        h.write('// Generated by web/prune.py: no-op initializers for modules cut from the link.\n')
        h.write('#include <lean/lean.h>\n')
        for s in sorted(stubs):
            h.write(f'lean_object * {s}(uint8_t builtin) {{ return lean_io_result_mk_ok(lean_box(0)); }}\n')
    with open(os.path.join(outdir, 'sources.txt'), 'w') as h:
        h.write('\n'.join(sources) + '\n')

    by = collections.Counter(
        f.split('/packages/')[1].split('/')[0] if '/packages/' in f else os.path.basename(os.path.dirname(f))
        for f in files)
    print(f'prune.py: linking {len(files)} modules {dict(by)}; cut {len(stubs)}', file=sys.stderr)
    print(entry)


if __name__ == '__main__':
    main()
